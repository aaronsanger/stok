WITH STOK AS (
	SELECT WIL AS WILSTK, DEPO AS DEPOSTK, GRUPGAB, KATEGORI, KELOMPOK, ITEMGB, SUM(QTYNETSTOK) AS QTYNETSTOK
	FROM {{DB_SCHEMA}}.{{TABLE_STOK}}
	WHERE DIVISI IN ('{{DIVISI_CODE}}') AND QTYNETSTOK > 0
	GROUP BY 1,2,3,4,5,6
	ORDER BY 1,2,4,7 DESC,6
), 
DB AS (
	SELECT DB.WIL AS WIL, DB.DEPO AS DEPO
	FROM {{DB_SCHEMA}}.{{TABLE_OMS}} AS DB
	WHERE DIVISI IN ('{{DIVISI_CODE}}')
			AND THN IN ({{FILTER_YEAR}}) AND BLN IN ({{FILTER_MONTH}})
			AND grupgab NOT IN ({{EXCLUDED_GROUPS}})
	GROUP BY 1,2
)
SELECT *
FROM DB
LEFT JOIN STOK AS STK ON LEFT(DB.WIL,2) = LEFT(STK.WILSTK,2) AND LEFT(DB.DEPO,4) = LEFT(STK.DEPOSTK,4)
WHERE CONCAT(LEFT(DB.WIL,2), LEFT(DB.DEPO,4)) = '{{KEY}}'
ORDER BY 6, 9 DESC, 8
